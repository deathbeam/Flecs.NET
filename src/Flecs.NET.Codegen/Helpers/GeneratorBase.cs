using Microsoft.CodeAnalysis;

namespace Flecs.NET.Codegen.Helpers;

public abstract class GeneratorBase
{
    private IncrementalGeneratorPostInitializationContext _context;

    public abstract void Generate();

    internal void Generate(IncrementalGeneratorPostInitializationContext context)
    {
        _context = context;
        Generate();
    }

    public void AddSource(string file, string source)
    {
        string typeName = GetType().Name;

        _context.AddSource($"{typeName}/{file}", $$"""
            // /_/src/Flecs.NET/Generated/{{typeName}}/{{file}}
            // File was auto-generated by /_/src/Flecs.NET.Codegen/Generators/{{typeName}}.cs
            {{source}}
            """);
    }
}
