using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Flecs.NET.Sourcegen;

/// <summary>
///     Emits a <c>[ModuleInitializer]</c> registrar per <c>[FlecsStruct]</c> struct. Types that cannot
///     be reflected are skipped here; <see cref="StructReflectionAnalyzer"/> reports them.
/// </summary>
[Generator]
public sealed class StructReflectionGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<StructModel> models = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                StructReflectionRules.AttributeFullyQualifiedName,
                static (node, _) => node is TypeDeclarationSyntax,
                static (attributeContext, _) => Transform(attributeContext))
            .Where(static model => model.HasValue)
            .Select(static (model, _) => model!.Value);

        context.RegisterSourceOutput(models, static (spc, model) => spc.AddSource(model.GeneratedFileName, model.Source));
    }

    private static StructModel? Transform(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol { TypeKind: TypeKind.Struct } symbol)
            return null;

        ReflectionResult result = StructReflectionRules.Analyze(symbol);
        return result.Problem == ReflectionProblem.None ? BuildModel(result) : null;
    }

    private static StructModel BuildModel(ReflectionResult result)
    {
        string sanitized = SanitizeIdentifier(result.TypeName);
        string className = $"__FlecsStructReflection_{sanitized}";

        var statements = new StringBuilder();
        foreach (ReflectedMember member in result.Members)
        {
            if (statements.Length > 0)
                statements.Append('\n');

            statements.Append("                component.Member<")
                .Append(member.Type)
                .Append(">(\"")
                .Append(member.Name)
                .Append('"');

            if (member.Count > 0)
                statements.Append(", ").Append(member.Count);

            statements.Append(");");
        }

        // An [InlineArray] type is a flecs array type, so it gets an array registration instead of members.
        string registration = result.ElementType is { } elementType
            ? $"        global::Flecs.NET.Core.StructReflection<{result.TypeName}>.RegisterArray<{elementType}>({result.ElementCount});"
            : $$"""
                            global::Flecs.NET.Core.StructReflection<{{result.TypeName}}>.Register(
                                static component =>
                                {
                    {{statements}}
                                });
                    """;

        string source = $$"""
            // <auto-generated/>
            #nullable enable

            using System.Runtime.CompilerServices;

            namespace Flecs.NET.Generated.StructReflection;

            internal static class {{className}}
            {
                [ModuleInitializer]
                internal static void __Register()
                {
            {{registration}}
                }
            }
            """;

        return new StructModel($"StructReflection.{sanitized}.g.cs", source);
    }

    // Reversible escaping, so distinct type names (e.g. A.B_C vs A_B.C) never share a file or class name.
    private static string SanitizeIdentifier(string fullyQualifiedName)
    {
        var builder = new StringBuilder(fullyQualifiedName.Length);

        foreach (char c in fullyQualifiedName)
        {
            if (c == '_')
                builder.Append("__");
            else if (c == '.')
                builder.Append("_d");
            else if (c == ':')
                builder.Append("_c");
            else if (char.IsLetterOrDigit(c))
                builder.Append(c);
            else
                builder.Append("_u").Append(((int)c).ToString("X4"));
        }

        return builder.ToString();
    }

    // Cached data is equatable strings only, so no syntax tree or symbol is rooted by the generator.
    private readonly struct StructModel : IEquatable<StructModel>
    {
        public string GeneratedFileName { get; }
        public string Source { get; }

        public StructModel(string generatedFileName, string source)
        {
            GeneratedFileName = generatedFileName;
            Source = source;
        }

        public bool Equals(StructModel other)
            => GeneratedFileName == other.GeneratedFileName && Source == other.Source;

        public override bool Equals(object? obj) => obj is StructModel other && Equals(other);

        public override int GetHashCode() => GeneratedFileName.GetHashCode();
    }
}
